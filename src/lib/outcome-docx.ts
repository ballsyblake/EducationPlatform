/**
 * The coach assessment outcome sheets as a Word file.
 *
 * FQ circulate theirs as .docx — Karl Dodd's `C - LICENCE COACH ASSESSMENT`
 * was generated by python-docx off a register — because a Word file is a thing
 * other people open, edit and sign, which a printed page is not. So the export
 * button hands back the real format rather than a PDF somebody then has to
 * retype.
 *
 * Built from the same `OutcomeSheet` the page renders, through the same
 * `outcomeSheetFor` and `courseOutcomeSheets`, so the two cannot disagree
 * about *what* is on a coach's record. What they do each own is the layout,
 * and that is the duplication worth naming: `src/components/outcome-sheet.tsx`
 * lays the sheet out in HTML and this lays it out in Word. When a field moves,
 * move it in both.
 *
 * Nothing is decided here. An outcome prints where the rubric has one and the
 * boxes come back empty where it does not, exactly as on the page.
 */

/* ------------------------------- Brand ----------------------------------- */

// Football Queensland's Deep Maroon, matching `--color-maroon-800` in
// globals.css. docx wants bare hex, no leading hash.
const MAROON = "621333";
const INK = "3D3D3D";
const MUTED = "6B6B6B";
const RULE = "D4D4D4";

// Gibson is the brand typeface and is licensed, so it is not bundled; the
// guidelines name Arial as the substitute, which is what `--font-brand` falls
// back to on the page.
const FONT = "Arial";

/** Half-points, which is what docx sizes are in. */
const pt = (n: number) => n * 2;

const THIN = { style: BorderStyle.SINGLE, size: 4, color: RULE };
const CELL_BORDERS = { top: THIN, bottom: THIN, left: THIN, right: THIN };
const NO_BORDERS = {
  top: { style: BorderStyle.NONE, size: 0, color: "auto" },
  bottom: { style: BorderStyle.NONE, size: 0, color: "auto" },
  left: { style: BorderStyle.NONE, size: 0, color: "auto" },
  right: { style: BorderStyle.NONE, size: 0, color: "auto" },
};

const FULL_WIDTH = { size: 100, type: WidthType.PERCENTAGE };

type TextOpts = {
  bold?: boolean;
  size?: number;
  color?: string;
  caps?: boolean;
  before?: number;
  after?: number;
  align?: (typeof AlignmentType)[keyof typeof AlignmentType];
};

function text(content: string, o: TextOpts = {}) {
  return new TextRun({
    text: o.caps ? content.toUpperCase() : content,
    bold: o.bold,
    size: pt(o.size ?? 9),
    color: o.color ?? INK,
    font: FONT,
  });
}

function para(content: string | TextRun[], o: TextOpts = {}) {
  return new Paragraph({
    children: typeof content === "string" ? [text(content, o)] : content,
    alignment: o.align,
    spacing: { before: pt(o.before ?? 0), after: pt(o.after ?? 2) },
  });
}

/** A cell, since every one of them wants the same borders and padding. */
function cell(
  children: Paragraph[],
  o: { width?: number; shaded?: boolean } = {},
) {
  return new TableCell({
    children,
    borders: CELL_BORDERS,
    shading: o.shaded ? { fill: "F7F7F7" } : undefined,
    width: o.width ? { size: o.width, type: WidthType.PERCENTAGE } : undefined,
    margins: { top: 40, bottom: 40, left: 80, right: 80 },
  });
}

/** The maroon section band FQ's form rules each block off with. */
function heading(label: string) {
  return new Table({
    width: FULL_WIDTH,
    rows: [
      new TableRow({
        children: [
          new TableCell({
            children: [
              para(label, { bold: true, size: 8, color: "FFFFFF", caps: true }),
            ],
            shading: { fill: MAROON },
            borders: CELL_BORDERS,
            margins: { top: 40, bottom: 40, left: 80, right: 80 },
          }),
        ],
      }),
    ],
  });
}

/* ------------------------------ The sheet -------------------------------- */

/** The form's 2x3 block of facts. */
function facts(delivery: OutcomeDelivery) {
  const fields: [string, string | null][] = [
    ["Assessor", delivery.assessor],
    ["Block / when", delivery.block],
    ["Component", delivery.component],
    ["Topic", delivery.topic],
    ["Date", delivery.date],
    ["Session", delivery.session],
  ];
  const rows: TableRow[] = [];
  for (let i = 0; i < fields.length; i += 2) {
    rows.push(
      new TableRow({
        children: fields.slice(i, i + 2).map(([label, value]) =>
          cell(
            [
              para([
                text(`${label}: `, {
                  bold: true,
                  size: 8,
                  color: MUTED,
                  caps: true,
                }),
                text(value ?? "", { size: 9 }),
              ]),
            ],
            { width: 50 },
          ),
        ),
      }),
    );
  }
  return new Table({ width: FULL_WIDTH, rows });
}

/** The six areas and their marks, with the total under them. */
function scoresheet(points: NonNullable<OutcomeDelivery["points"]>) {
  const rows = points.areas.map(
    (area) =>
      new TableRow({
        children: [
          cell([para(area.title, { size: 9 })], { width: 80 }),
          // A blank area is not a nought — see `totalPoints`.
          cell([para(`${area.score ?? "—"} / 3`, { size: 9 })], { width: 20 }),
        ],
      }),
  );
  rows.push(
    new TableRow({
      children: [
        cell([para("Total", { bold: true, size: 8, caps: true })], {
          width: 80,
          shaded: true,
        }),
        cell(
          [para(`${points.scored} / ${points.total}`, { bold: true, size: 9 })],
          {
            width: 20,
            shaded: true,
          },
        ),
      ],
    }),
  );
  return new Table({ width: FULL_WIDTH, rows });
}

/** A free-text box with room to write in it, as the form prints one. */
function box(content: string | null) {
  return new Table({
    width: FULL_WIDTH,
    rows: [new TableRow({ children: [cell(bodyLines(content))] })],
  });
}

/** Newlines are paragraphs in Word; one empty paragraph keeps a blank box open. */
function bodyLines(content: string | null) {
  const lines = (content ?? "").split("\n");
  return lines.map((line) => para(line, { size: 9 }));
}

/** The outcome row. An empty box is a box somebody still has to tick. */
function outcomeBoxes(ticked: string | null) {
  const runs: TextRun[] = [];
  for (const label of ["Highly Competent", "Competent", "Not Yet Competent"]) {
    const on = label === ticked;
    runs.push(
      text(on ? "[X] " : "[  ] ", { bold: true, size: 10, color: MAROON }),
    );
    runs.push(text(`${label}    `, { bold: on, size: 9 }));
  }
  return para(runs, { before: 4 });
}

function deliveryBlock(delivery: OutcomeDelivery, only: boolean) {
  const out: (Paragraph | Table)[] = [];

  if (!only) {
    out.push(
      para(`Delivery ${delivery.deliveryNo}`, {
        bold: true,
        size: 8,
        color: MAROON,
        caps: true,
        before: 8,
      }),
    );
  }
  out.push(facts(delivery));

  if (delivery.points) {
    out.push(heading(`Assessment — six areas, ${MAX_DELIVERY_POINTS} points`));
    out.push(scoresheet(delivery.points));
    out.push(
      para(
        delivery.points.complete && delivery.points.outcome
          ? `This session: ${delivery.points.scored} / ${delivery.points.total} — ${delivery.points.outcome.label}.`
          : "Not every area has been scored, so this session has no outcome yet. A blank area is not a nought.",
        { size: 8, color: MUTED },
      ),
    );
  }

  // Outside the scoresheet on purpose: the 2026 registers carry a 1-5 session
  // rating and no area scores at all, so a rating printed only beside a
  // scoresheet is a rating that never prints for the intakes already imported.
  if (delivery.rating !== null) {
    out.push(
      para(
        `Rated ${delivery.rating.toFixed(1)} / 5 on the register.` +
          (delivery.points
            ? ""
            : " This session has not been scored on the six areas."),
        { size: 8, color: MUTED },
      ),
    );
  }

  out.push(heading("Assessor comment / evidence"));
  out.push(box(delivery.comment));

  out.push(heading("Action plan"));
  // Three rows whether or not three were written: a plan with room left on it
  // reads as a plan rather than a finished list.
  out.push(
    new Table({
      width: FULL_WIDTH,
      rows: [0, 1, 2].map(
        (i) =>
          new TableRow({
            children: [
              cell([
                para([
                  text(`${i + 1}. `, { bold: true, size: 9, color: MUTED }),
                  text(delivery.actions[i] ?? "", { size: 9 }),
                ]),
              ]),
            ],
          }),
      ),
    }),
  );

  return out;
}

/** A coach nobody has written up still gets a form to take to the grass. */
const BLANK_DELIVERY: OutcomeDelivery = {
  deliveryNo: 1,
  assessor: null,
  block: null,
  component: null,
  topic: null,
  session: null,
  date: null,
  comment: null,
  actions: [],
  rating: null,
  points: null,
};

/**
 * The caveat that belongs under a sheet, where there is one.
 *
 * Football Australia published the competency line for the B and A Diplomas
 * but not the Highly Competent one, so those two follow the C Diploma's
 * three-point step and the document has to admit it. On a C Diploma, and on a
 * course whose level nothing names, there is nothing to say here that the
 * grading band has not already said.
 */
function sheetFootnote(sheet: OutcomeSheet) {
  if (sheet.thresholds.assumed) {
    return "Nothing on this course names its diploma, so the C Diploma's lines are the ones applied above.";
  }
  if (sheet.thresholds.inferred) {
    return (
      "Football Australia has published the competency line for this diploma but not the " +
      "Highly Competent one, which follows the C Diploma's three-point step."
    );
  }
  return "Six areas, scored on a best fit of what the session showed, and never averaged.";
}

function thresholdSentence(sheet: OutcomeSheet) {
  const { thresholds } = sheet;
  const lines = thresholds.assumed
    ? "Nothing on this course names its diploma, so the C Diploma's lines apply:"
    : `On a ${sheet.qualification}:`;
  let out =
    `Six areas, ${MAX_DELIVERY_POINTS} points in all, scored on a best fit of what the session ` +
    `showed and never averaged. ${lines} under ${thresholds.competent} is Not Yet Competent, ` +
    `${thresholds.competent} to ${thresholds.highlyCompetent - 1} is Competent, and ` +
    `${thresholds.highlyCompetent} or more is Highly Competent.`;
  if (thresholds.inferred) {
    out +=
      " Football Australia has published the competency line for this diploma but not the " +
      "Highly Competent one, which follows the C Diploma's three-point step.";
  }
  return out;
}

function sheetBlocks(sheet: OutcomeSheet, first: boolean) {
  const out: (Paragraph | Table)[] = [];

  if (!first) out.push(new Paragraph({ children: [new PageBreak()] }));

  // The title that was here has gone into the running header, which is where
  // FQ's template carries it and means it appears on a coach's second page too.
  out.push(candidateBlock(sheet));
  out.push(gradingBand(sheet));

  const deliveries = sheet.deliveries.length
    ? sheet.deliveries
    : [BLANK_DELIVERY];
  for (const delivery of deliveries) {
    out.push(...deliveryBlock(delivery, deliveries.length === 1));
  }

  // The thresholds stay on every sheet — they are what makes the outcome
  // self-evidencing — but the four-rung table does not. Repeated per coach it
  // was tall enough to tip each sheet onto a second page, which on a
  // thirty-five coach cohort is thirty-five pages carrying a guide somebody
  // has already read. It opens the document instead; see `coverBlocks`.
  out.push(
    // Only the caveat. The grading band at the head of the sheet already
    // states the three ranges in FQ's own shape, and printing the same numbers
    // again as prose was what tipped a one-delivery sheet onto a second page.
    para(sheetFootnote(sheet), { size: 7, color: MUTED, before: 4 }),
  );

  out.push(heading("Overall"));
  const assessed = sheet.assessed;
  out.push(
    para(
      assessed
        ? `${assessed.points.scored} / ${assessed.points.total}`
        : `— / ${MAX_DELIVERY_POINTS}`,
      {
        bold: true,
        size: 14,
        color: MAROON,
      },
    ),
  );
  out.push(outcomeBoxes(assessed?.points.outcome?.label ?? null));

  if (assessed) {
    if (sheet.deliveries.length > 1) {
      out.push(
        para(
          `Read off delivery ${assessed.deliveryNo}, the most recent session scored in full. ` +
            "Totals are never averaged across sessions, so one assessment carries the outcome " +
            "and the others above it are the evidence it was reached through.",
          { size: 8, color: MUTED },
        ),
      );
    }
  } else {
    out.push(
      para(
        "No session has been scored in full yet, so there is no outcome to read. The boxes " +
          "above are for an assessor to complete.",
        { size: 8, color: MUTED },
      ),
    );
  }

  if (sheet.rating !== null && sheet.band) {
    out.push(
      para(
        `Separately, the course rating on the register is ${sheet.rating.toFixed(1)} / 5 — ` +
          `${sheet.band.outcome.toLowerCase()}. It is a judgement across everything this coach ` +
          "delivered rather than a total of their sessions, and it does not convert to the " +
          "points above.",
        { size: 8, color: MUTED },
      ),
    );
  }

  // Not stored anywhere, so it prints as a rule to sign rather than as a name
  // the app has put in somebody's mouth. One paragraph rather than a table: a
  // two-cell table with room to sign in it was tall enough to tip every sheet
  // onto a second page.
  out.push(
    para(
      [
        text("______________________________  ", { size: 9, color: MUTED }),
        text("Assessor signature and date", { size: 8, color: MUTED }),
        text("      ______________________________  ", {
          size: 9,
          color: MUTED,
        }),
        text("Coach acknowledgement and date", { size: 8, color: MUTED }),
      ],
      { before: 10 },
    ),
  );

  return out;
}

/** The front page of a whole-cohort file: what it is, and the rubric it uses. */
function coverBlocks(sheets: OutcomeSheet[], courseTitle: string) {
  const first = sheets[0];
  const out: (Paragraph | Table)[] = [
    para(
      first ? `${first.qualification} coach assessment` : "Coach assessment",
      {
        bold: true,
        size: 18,
        color: MAROON,
        caps: true,
      },
    ),
    para(courseTitle, { size: 10 }),
  ];
  if (first?.location)
    out.push(para(first.location, { size: 9, color: MUTED }));
  out.push(
    para(
      `${sheets.length} coach${sheets.length === 1 ? "" : "es"}, one sheet each`,
      {
        size: 9,
        color: MUTED,
      },
    ),
  );

  out.push(
    para("Assessment rating guide", {
      bold: true,
      size: 10,
      color: MAROON,
      caps: true,
      before: 16,
    }),
  );
  out.push(
    new Table({
      width: FULL_WIDTH,
      rows: [
        new TableRow({
          children: [
            cell([para("Score", { bold: true, size: 9 })], {
              width: 10,
              shaded: true,
            }),
            cell([para("Level", { bold: true, size: 9 })], {
              width: 22,
              shaded: true,
            }),
            cell([para("What it means", { bold: true, size: 9 })], {
              width: 68,
              shaded: true,
            }),
          ],
        }),
        ...DELIVERY_LEVELS.map(
          (level) =>
            new TableRow({
              children: [
                cell([para(String(level.score), { bold: true, size: 9 })], {
                  width: 10,
                }),
                cell([para(level.label, { size: 9 })], { width: 22 }),
                cell([para(level.description, { size: 9 })], { width: 68 }),
              ],
            }),
        ),
      ],
    }),
  );
  if (first)
    out.push(
      para(thresholdSentence(first), { size: 9, color: MUTED, before: 8 }),
    );
  return out;
}

/* ------------------------------- Chrome ---------------------------------- */

/**
 * Football Queensland's master logo, for the page header.
 *
 * The same file the app serves at `/brand/fq-logo-horizontal.png`, read off
 * disk rather than fetched: this runs on the server that would be answering
 * the request, and a document that silently loses its letterhead because the
 * app could not reach itself is worse than one that throws while being built.
 *
 * Read once. It is 80KB and every sheet in a thirty-five coach export would
 * otherwise read it again.
 */
let logoCache: Buffer | null | undefined;

async function fqLogo() {
  if (logoCache !== undefined) return logoCache;
  try {
    logoCache = await readFile(
      path.join(process.cwd(), "public", "brand", "fq-logo-horizontal.png"),
    );
  } catch {
    // The guidelines are explicit that nothing may stand in for the mark, so a
    // missing file means a header with no logo rather than a drawn one.
    logoCache = null;
  }
  return logoCache;
}

/** The logo's own proportions, 2640x1021, at a sensible height on the page. */
const LOGO = { width: 132, height: 51 };

/**
 * The letterhead, repeated on every page.
 *
 * Laid out as FQ's own `'C' DIPLOMA PRACTICAL COACHING ASSESSMENT` template
 * does it: the mark on the left, the document's own name on the right, and a
 * maroon rule under both.
 */
async function letterhead(title: string) {
  const logo = await fqLogo();
  return new Header({
    children: [
      new Table({
        width: FULL_WIDTH,
        borders: {
          ...NO_BORDERS,
          bottom: { style: BorderStyle.SINGLE, size: 12, color: MAROON },
          insideHorizontal: { style: BorderStyle.NONE, size: 0, color: "auto" },
          insideVertical: { style: BorderStyle.NONE, size: 0, color: "auto" },
        },
        rows: [
          new TableRow({
            children: [
              new TableCell({
                borders: NO_BORDERS,
                width: { size: 40, type: WidthType.PERCENTAGE },
                margins: { top: 0, bottom: 80, left: 0, right: 0 },
                children: [
                  new Paragraph({
                    children: logo
                      ? [
                          new ImageRun({
                            data: new Uint8Array(logo),
                            transformation: LOGO,
                            type: "png",
                            altText: {
                              title: "Football Queensland",
                              description: "Football Queensland",
                              name: "Football Queensland",
                            },
                          }),
                        ]
                      : [
                          text("Football Queensland", {
                            bold: true,
                            size: 11,
                            color: MAROON,
                          }),
                        ],
                    spacing: { before: 0, after: 0 },
                  }),
                ],
              }),
              new TableCell({
                borders: NO_BORDERS,
                width: { size: 60, type: WidthType.PERCENTAGE },
                verticalAlign: VerticalAlign.BOTTOM,
                margins: { top: 0, bottom: 80, left: 0, right: 0 },
                children: [
                  para(title, {
                    bold: true,
                    size: 12,
                    color: MAROON,
                    caps: true,
                    align: AlignmentType.RIGHT,
                  }),
                ],
              }),
            ],
          }),
        ],
      }),
    ],
  });
}

/** The document's name and the page number, as FQ's template foots a page. */
function footer(title: string) {
  return new Footer({
    children: [
      new Paragraph({
        alignment: AlignmentType.RIGHT,
        border: { top: { style: BorderStyle.SINGLE, size: 4, color: RULE } },
        spacing: { before: pt(4), after: 0 },
        children: [
          text(`${title}    `, { size: 7, color: MUTED }),
          new TextRun({
            children: [
              "Page ",
              PageNumber.CURRENT,
              " of ",
              PageNumber.TOTAL_PAGES,
            ],
            size: pt(7),
            color: MUTED,
            font: FONT,
          }),
        ],
      }),
    ],
  });
}

/**
 * The candidate block FQ's template opens with.
 *
 * Their four fields — name, accreditation level, course date, location —
 * rather than our own line of text under the name, because this is the part of
 * their paperwork somebody reads first and files by.
 */
function candidateBlock(sheet: OutcomeSheet) {
  const field = (label: string, value: string | null, width: number) =>
    cell(
      [
        para(label, { bold: true, size: 8, color: MUTED, caps: true }),
        para(value || "", { size: 10 }),
      ],
      { width },
    );
  return new Table({
    width: FULL_WIDTH,
    rows: [
      new TableRow({
        children: [
          field("Candidate name", sheet.name, 50),
          field("Accreditation level", sheet.qualification, 50),
        ],
      }),
      new TableRow({
        children: [
          field("Course", sheet.courseTitle, 50),
          field("Course location", sheet.location || sheet.clubName, 50),
        ],
      }),
    ],
  });
}

/**
 * The grading scale as one ruled row, which is how their template states it.
 *
 * On the page rather than in a sentence: an assessor reading a total wants the
 * three bands side by side, and the document then evidences its own outcome.
 */
function gradingBand(sheet: OutcomeSheet) {
  const { thresholds } = sheet;
  const band = (label: string, range: string) =>
    cell(
      [
        para(label, { bold: true, size: 8 }),
        para(range, { size: 8, color: MUTED }),
      ],
      {
        width: 30,
      },
    );
  return new Table({
    width: FULL_WIDTH,
    rows: [
      new TableRow({
        children: [
          cell([para("Grading", { bold: true, size: 8, caps: true })], {
            width: 10,
            shaded: true,
          }),
          band("NYC — Not Yet Competent", `0–${thresholds.competent - 1}`),
          band(
            "C — Competent",
            `${thresholds.competent}–${thresholds.highlyCompetent - 1}`,
          ),
          band(
            "HC — Highly Competent",
            `${thresholds.highlyCompetent}–${MAX_DELIVERY_POINTS}`,
          ),
        ],
      }),
    ],
  });
}

/* ------------------------------- Packing --------------------------------- */

/**
 * One coach's sheet, or a whole cohort's with a cover in front.
 *
 * `courseTitle` turns it into the cohort file: a single coach is handed over
 * on its own, the way an educator exports one, and twenty-five get a front
 * page so the file says what it is before the first name.
 */
export async function outcomeDocx(
  sheets: OutcomeSheet[],
  courseTitle?: string,
) {
  const children: (Paragraph | Table)[] = [];
  if (courseTitle) {
    children.push(...coverBlocks(sheets, courseTitle));
    sheets.forEach((sheet) => children.push(...sheetBlocks(sheet, false)));
  } else {
    sheets.forEach((sheet, i) => children.push(...sheetBlocks(sheet, i === 0)));
  }

  // What the letterhead and the footer say. A cohort file is named for its
  // course; a single coach's is named for the accreditation, which is what
  // FQ's own template puts up there.
  const title =
    courseTitle ??
    (sheets[0]
      ? `${sheets[0].qualification} coach assessment`
      : "Coach assessment");

  const doc = new Document({
    styles: {
      default: {
        document: { run: { font: FONT, size: pt(9), color: INK } },
      },
    },
    sections: [
      {
        properties: {
          page: {
            // Room for the running header and footer above and below the
            // margin the sheet itself is laid out inside.
            margin: {
              top: 1500,
              bottom: 1100,
              left: 800,
              right: 800,
              header: 560,
              footer: 560,
            },
          },
        },
        headers: { default: await letterhead(title) },
        footers: { default: footer(title) },
        children: children.length ? children : [para("Nothing to print.")],
      },
    ],
  });

  return Packer.toBuffer(doc);
}

/**
 * A filename somebody can find again on their desktop.
 *
 * Anything a filesystem argues with becomes a hyphen — Word on Windows refuses
 * a name with a colon in it, and FQ's course titles carry them — and the whole
 * thing is kept short. A cohort's full title plus a suffix ran past a hundred
 * characters once percent-encoded, and Chromium gave up on the header and
 * saved the file as "download"; callers pass a shortened title for the same
 * reason.
 */
const MAX_STEM = 60;

export function docxFilename(...parts: (string | null | undefined)[]) {
  let stem = parts
    .filter(Boolean)
    .join(" - ")
    .replace(/[\\/:*?"<>|]+/g, "-")
    .replace(/\s+/g, " ")
    .trim();
  if (stem.length > MAX_STEM) stem = `${stem.slice(0, MAX_STEM).trimEnd()}…`;
  return `${stem || "coach-assessment"}.docx`;
}
