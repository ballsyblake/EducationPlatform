import { staffCourseIds } from "@/lib/access";
import { prisma } from "@/lib/db";
import { MAX_DELIVERY_POINTS, outcomeFor, thresholdsFor, totalPoints } from "@/lib/delivery-rubric";
import { displayName } from "@/lib/format";
import { bandFor, RATING_SCALE, type Band } from "@/lib/support-rubric";
import type { User } from "@prisma-client";

/**
 * The coach assessment outcome document, assembled out of what the register
 * already holds.
 *
 * This is FQ's own `C - LICENCE COACH ASSESSMENT` paperwork — one page per
 * coach, a photo and a name across the top, the facts about the delivery that
 * was watched, the 1-5 rating guide, the assessor's evidence, the action plan,
 * and an overall rating with Highly Competent / Competent / Not Yet Competent
 * beside it. Karl Dodd's copy of 15 October 2026 was generated by python-docx
 * off a register, which is the whole reason this belongs in the app: every
 * field on it is a column the platform already keeps.
 *
 * Nothing here decides anything. The rating is `Enrollment.rating`, which a
 * person sets; the FA band is `bandFor` reading the rubric; the deliveries are
 * whatever has been written up. A field nobody has filled in prints blank, the
 * way it does on the paper form — a document that quietly invented the missing
 * half of a coach's assessment would be worse than one with gaps in it.
 */

/** One delivery, as the form's session block reads it. */
export type OutcomeDelivery = {
  deliveryNo: number;
  assessor: string | null;
  block: string | null;
  component: string | null;
  topic: string | null;
  session: string | null;
  /// Already formatted: the sheet is print-only and never parses it back.
  date: string | null;
  comment: string | null;
  /// Up to three, numbered by the sheet rather than stored numbered.
  actions: string[];
  /// The session's own 1-5 mark, which is not the coach's course rating.
  rating: number | null;
  /**
   * Football Australia's six-area scoresheet, where it has been filled in.
   *
   * Not on FQ's template — their C Licence form carries only the 1-5 rating —
   * but it is the evidence the rating was formed from and the platform's
   * assessors enter it on the same screen. Printed under the evidence box and
   * labelled as the rubric record, so nobody reads a session's 11/18 as the
   * outcome of the course.
   */
  points: { scored: number; total: number; outcome: string; complete: boolean } | null;
};

/** One coach's sheet. */
export type OutcomeSheet = {
  enrollmentId: string;
  name: string;
  email: string;
  photoId: string | null;
  clubName: string | null;
  /// "C Licence", "B Diploma" — what the header band says.
  qualification: string;
  courseTitle: string;
  location: string | null;
  deliveries: OutcomeDelivery[];
  /**
   * The coach's course rating, 1-5.
   *
   * FQ's form labels this box `OVERALL RATING (1-5)` on a page that otherwise
   * describes a single session, which reads two ways. It is filled from
   * `Enrollment.rating` — the judgement across everything the coach delivered —
   * because that is the number the register carries forward and the one the
   * outcome follows from. Each session's own mark prints beside that session.
   */
  rating: number | null;
  band: Band | null;
};

/** A row of the sheet's rating guide. */
export type GuideRow = {
  rating: number;
  /// Only on the top row of each FA band, which is the row that carries its name.
  faRating: string | null;
  /**
   * Only where this step starts a band in `RATING_BANDS`.
   *
   * The rubric defines six of those inside three FA bands — "top Tier 1 club
   * coach" and "average Tier 1 club coach" are different descriptions of the
   * same competency — so a description belongs to the step, not to the FA
   * wording above it.
   */
  description: string | null;
};

/**
 * The guide FQ prints above the evidence box, rendered from the rubric.
 *
 * Every half step on the scale, highest first, grouped by the FA wording
 * `bandFor` gives it. Built rather than transcribed so the guide a coach is
 * handed and the band the app applies cannot drift apart — but note that FQ's
 * own C Licence sheet draws the Highly Competent line at 4 and this draws it
 * where `RATING_BANDS` draws it, at 3.5. The bands in `support-rubric.ts` are
 * transcribed from the B Diploma rubric inside the attendance register; FQ has
 * not said whether the C Licence line is deliberately different or whether one
 * of the two documents is out of date. Until somebody asks them, the app's own
 * bands are what prints, because they are what every other page already shows.
 */
export const RATING_GUIDE: GuideRow[] = RATING_SCALE.slice()
  .reverse()
  .map((rating, index, all) => {
    const band = bandFor(rating);
    const newFaBand = index === 0 || bandFor(all[index - 1])?.faRating !== band?.faRating;
    return {
      rating,
      faRating: newFaBand ? (band?.faRating ?? null) : null,
      description: band?.min === rating ? band.definition : null,
    };
  });

const SHEET_DATE = new Intl.DateTimeFormat("en-AU", {
  day: "2-digit",
  month: "2-digit",
  year: "numeric",
});

/** The form writes a plain `__ / __ / ____`, so the sheet does too. */
function sheetDate(date: Date | null) {
  return date ? SHEET_DATE.format(date) : null;
}

/** The numbering the action plan is written with, taken back off for printing. */
function planSteps(actionPlan: string | null) {
  if (!actionPlan) return [];
  return actionPlan
    .split("\n")
    .map((line) => line.replace(/^\s*\d+[.)]\s*/, "").trim())
    .filter(Boolean);
}

/** What Prisma has to hand back for `toSheet` to build a page from it. */
const SHEET_INCLUDE = {
  user: true,
  course: true,
  deliveries: { orderBy: { deliveryNo: "asc" }, include: { scores: true } },
} as const;

type SheetRow = {
  id: string;
  clubName: string | null;
  rating: number | null;
  user: { name: string | null; email: string; photoId: string | null };
  course: { title: string; qualification: string | null; location: string | null };
  deliveries: {
    deliveryNo: number;
    assessor: string | null;
    block: string | null;
    component: string | null;
    topic: string | null;
    session: string | null;
    deliveredOn: Date | null;
    comment: string | null;
    actionPlan: string | null;
    rating: number | null;
    scores: { code: string; score: number }[];
  }[];
};

function toSheet(enrollment: SheetRow): OutcomeSheet {
  const thresholds = thresholdsFor(enrollment.course);

  return {
    enrollmentId: enrollment.id,
    name: displayName(enrollment.user),
    email: enrollment.user.email,
    photoId: enrollment.user.photoId,
    clubName: enrollment.clubName,
    // The header band names the accreditation. Falling back to the course title
    // rather than to "C Licence": a B Diploma cohort printed under a C Licence
    // header is a document that misstates what the coach was assessed on.
    qualification: enrollment.course.qualification?.trim() || enrollment.course.title,
    courseTitle: enrollment.course.title,
    location: enrollment.course.location,
    rating: enrollment.rating,
    band: bandFor(enrollment.rating),
    deliveries: enrollment.deliveries.map((d) => {
      const scored = totalPoints(new Map(d.scores.map((s) => [s.code, s.score])));
      return {
        deliveryNo: d.deliveryNo,
        assessor: d.assessor,
        block: d.block,
        component: d.component,
        topic: d.topic,
        session: d.session,
        date: sheetDate(d.deliveredOn),
        comment: d.comment,
        actions: planSteps(d.actionPlan),
        rating: d.rating,
        points:
          scored.scored > 0
            ? {
                scored: scored.points,
                total: MAX_DELIVERY_POINTS,
                // An incomplete sheet has no outcome — see `totalPoints`. Saying
                // so beats printing the outcome of a half-filled scoresheet.
                outcome: scored.complete
                  ? outcomeFor(scored.points, thresholds).label
                  : `${scored.scored} of 6 areas scored`,
                complete: scored.complete,
              }
            : null,
      };
    }),
  };
}

/**
 * One coach's sheet, for staff who are on their course.
 *
 * 404 rather than 403 for an educator off the roster, same as every other page
 * that reads an enrolment: the response must not confirm that this coach sat
 * this course to somebody with no business knowing it.
 */
export async function outcomeSheetFor(user: Pick<User, "id" | "role">, enrollmentId: string) {
  const enrollment = await prisma.enrollment.findUnique({
    where: { id: enrollmentId },
    include: SHEET_INCLUDE,
  });

  const scope = await staffCourseIds(user);
  if (!enrollment || (scope !== null && !scope.includes(enrollment.courseId))) notFound();

  return toSheet(enrollment);
}

/**
 * Every coach on a course, in register order, one sheet each.
 *
 * This is the shape of the file FQ circulates: twenty-five coaches in one
 * document, each on their own page. Catch-ups follow the main roster, which is
 * the order the register reads in.
 */
export async function courseOutcomeSheets(courseId: string) {
  const course = await prisma.course.findUnique({
    where: { id: courseId },
    include: {
      enrollments: { orderBy: { position: "asc" }, include: SHEET_INCLUDE },
    },
  });
  if (!course) notFound();

  const roster = [
    ...course.enrollments.filter((e) => e.track === "MAIN"),
    ...course.enrollments.filter((e) => e.track === "CATCH_UP"),
  ];

  return {
    course,
    sheets: roster.map(toSheet),
  };
}
