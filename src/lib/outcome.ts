/**
 * The coach assessment outcome document, assembled out of what the register
 * already holds.
 *
 * Laid out off FQ's own `C - LICENCE COACH ASSESSMENT` paperwork — one page per
 * coach, a photo and a name across the top, the facts about the delivery that
 * was watched, the assessor's evidence, the action plan, and an outcome of
 * Highly Competent / Competent / Not Yet Competent. Karl Dodd's copy of 15
 * October 2026 was generated by python-docx off a register, which is the whole
 * reason this belongs in the app: every field on it is a column the platform
 * already keeps.
 *
 * **Scored on Football Australia's rubric**, not on FQ's old 1-5 column. Six
 * areas at 0-3, eighteen points, and an outcome that follows from the total at
 * the diploma's own lines — which is the instrument the assessment form takes
 * and the one FQ moved to. The 1-5 course rating has not gone anywhere and
 * still prints: it is what the register carries forward and what decides
 * post-course support, and the two are not convertible, so the sheet shows both
 * and says which is which rather than picking one and implying the other.
 *
 * Nothing here decides anything. The scores are the assessor's, the outcome is
 * the rubric's arithmetic on them, and a field nobody has filled in prints
 * blank the way it does on the paper form.
 */

/** One area's mark on a scoresheet. */
export type OutcomeArea = {
  code: string;
  title: string;
  /// Null where that area was left unanswered, which is not a nought.
  score: number | null;
};

/** A scoresheet's total, and what it comes to. */
export type OutcomePoints = {
  scored: number;
  total: number;
  areas: OutcomeArea[];
  /// Null until all six areas carry a mark — an incomplete sheet has no outcome.
  outcome: DeliveryOutcome | null;
  complete: boolean;
};

/** One delivery, as the form's session block reads it. */
export type OutcomeDelivery = {
  deliveryNo: number;
  assessor: string | null;
  block: string | null;
  component: string | null;
  topic: string | null;
  session: string | null;
  /// Already formatted: the sheet is print-only and never parses it back.
  date: string | null;
  comment: string | null;
  /// Up to three, numbered by the sheet rather than stored numbered.
  actions: string[];
  /// The session's own 1-5 mark, where the register still carries one.
  rating: number | null;
  /// Null where nothing has been scored on the rubric at all.
  points: OutcomePoints | null;
};

/** One coach's sheet. */
export type OutcomeSheet = {
  enrollmentId: string;
  name: string;
  email: string;
  photoId: string | null;
  clubName: string | null;
  /// "C Licence", "B Diploma" — what the header band says.
  qualification: string;
  courseTitle: string;
  location: string | null;
  deliveries: OutcomeDelivery[];
  /// The diploma's own lines, and whether they had to be assumed.
  thresholds: ReturnType<typeof thresholdsFor>;
  /**
   * The delivery the outcome at the foot is read off, and its total.
   *
   * The most recently scored complete scoresheet. Totals are never averaged —
   * FA's guide is explicit, and a coach who scored 8 in March and 14 in June
   * has not delivered an eleven-point session — so a document covering a whole
   * course has to name one assessment as the assessed one rather than combine
   * them. The latest is the one the coach is at now; the earlier ones print
   * above it with their own totals, as the evidence it was reached through.
   *
   * Null where no scoresheet on this coach is complete, and the sheet then
   * prints no outcome rather than an outcome off a half-filled form.
   */
  assessed: { deliveryNo: number; points: OutcomePoints } | null;
  /**
   * The coach's course rating, 1-5, and its band on the register's own rubric.
   *
   * Secondary on this document now that the outcome comes off the eighteen
   * points, but not dropped: it is the number `courseResult` reads to decide
   * whether a coach passed or goes to post-course support, and leaving it off
   * the coach's own paperwork would hide the figure that decides that.
   */
  rating: number | null;
  band: Band | null;
};

const SHEET_DATE = new Intl.DateTimeFormat("en-AU", {
  day: "2-digit",
  month: "2-digit",
  year: "numeric",
});

/** The form writes a plain `__ / __ / ____`, so the sheet does too. */
function sheetDate(date: Date | null) {
  return date ? SHEET_DATE.format(date) : null;
}

/** The numbering the action plan is written with, taken back off for printing. */
function planSteps(actionPlan: string | null) {
  if (!actionPlan) return [];
  return (
    actionPlan
      .split("\n")
      .map((line) => line.replace(/^\s*\d+[.)]\s*/, "").trim())
      .filter(Boolean)
      // Some assessors number the steps with a bare digit and no stop — "1 Be
      // clear with the game rules" — which the strip above leaves alone, and
      // the sheet then prints "1. 1 Be clear…". Only taken off where the digit
      // is the step's own position, so an action that genuinely opens with a
      // number ("3 sessions a week on…") keeps it unless it happens to be the
      // third step.
      .map((step, i) => step.replace(new RegExp(`^${i + 1}\\s+(?=\\D)`), ""))
  );
}

/** What Prisma has to hand back for `toSheet` to build a page from it. */
const SHEET_INCLUDE = {
  user: true,
  course: true,
  deliveries: { orderBy: { deliveryNo: "asc" }, include: { scores: true } },
} as const;

type SheetRow = {
  id: string;
  clubName: string | null;
  rating: number | null;
  user: { name: string | null; email: string; photoId: string | null };
  course: {
    title: string;
    qualification: string | null;
    location: string | null;
  };
  deliveries: {
    deliveryNo: number;
    assessor: string | null;
    block: string | null;
    component: string | null;
    topic: string | null;
    session: string | null;
    deliveredOn: Date | null;
    comment: string | null;
    actionPlan: string | null;
    rating: number | null;
    scores: { code: string; score: number }[];
  }[];
};

function toSheet(enrollment: SheetRow): OutcomeSheet {
  const thresholds = thresholdsFor(enrollment.course);

  const deliveries: OutcomeDelivery[] = enrollment.deliveries.map((d) => {
    const byCode = new Map(d.scores.map((s) => [s.code, s.score]));
    const scored = totalPoints(byCode);
    return {
      deliveryNo: d.deliveryNo,
      assessor: d.assessor,
      block: d.block,
      component: d.component,
      topic: d.topic,
      session: d.session,
      date: sheetDate(d.deliveredOn),
      comment: d.comment,
      actions: planSteps(d.actionPlan),
      rating: d.rating,
      points:
        scored.scored > 0
          ? {
              scored: scored.points,
              total: MAX_DELIVERY_POINTS,
              areas: DELIVERY_AREAS.map((area) => ({
                code: area.code,
                title: area.title,
                score: byCode.get(area.code) ?? null,
              })),
              outcome: scored.complete
                ? outcomeFor(scored.points, thresholds)
                : null,
              complete: scored.complete,
            }
          : null,
    };
  });

  // The last complete scoresheet, which is the one the outcome is read off.
  const assessed =
    deliveries
      .filter((d) => d.points?.complete)
      .map((d) => ({
        deliveryNo: d.deliveryNo,
        points: d.points as OutcomePoints,
      }))
      .at(-1) ?? null;

  return {
    enrollmentId: enrollment.id,
    name: displayName(enrollment.user),
    email: enrollment.user.email,
    photoId: enrollment.user.photoId,
    clubName: enrollment.clubName,
    // The header band names the accreditation. Falling back to the course title
    // rather than to "C Licence": a B Diploma cohort printed under a C Licence
    // header is a document that misstates what the coach was assessed on.
    qualification:
      enrollment.course.qualification?.trim() || enrollment.course.title,
    courseTitle: enrollment.course.title,
    location: enrollment.course.location,
    thresholds,
    assessed,
    rating: enrollment.rating,
    band: bandFor(enrollment.rating),
    deliveries,
  };
}

/**
 * One coach's sheet, for staff who are on their course.
 *
 * 404 rather than 403 for an educator off the roster, same as every other page
 * that reads an enrolment: the response must not confirm that this coach sat
 * this course to somebody with no business knowing it.
 */
export async function outcomeSheetFor(
  user: Pick<User, "id" | "role">,
  enrollmentId: string,
) {
  const enrollment = await prisma.enrollment.findUnique({
    where: { id: enrollmentId },
    include: SHEET_INCLUDE,
  });

  const scope = await staffCourseIds(user);
  if (!enrollment || (scope !== null && !scope.includes(enrollment.courseId)))
    notFound();

  return toSheet(enrollment);
}

/**
 * Every coach on a course, in register order, one sheet each.
 *
 * This is the shape of the file FQ circulates: twenty-five coaches in one
 * document, each on their own page. Catch-ups follow the main roster, which is
 * the order the register reads in.
 */
export async function courseOutcomeSheets(courseId: string) {
  const course = await prisma.course.findUnique({
    where: { id: courseId },
    include: {
      enrollments: { orderBy: { position: "asc" }, include: SHEET_INCLUDE },
    },
  });
  if (!course) notFound();

  const roster = [
    ...course.enrollments.filter((e) => e.track === "MAIN"),
    ...course.enrollments.filter((e) => e.track === "CATCH_UP"),
  ];

  return {
    course,
    sheets: roster.map(toSheet),
  };
}
